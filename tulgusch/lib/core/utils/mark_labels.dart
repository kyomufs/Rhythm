/// Подписи аттестации приходят из API в свободной форме: «Отлично»,
/// «зачёт», «Незачет». Для таблиц и чипов нужна короткая и одинаковая
/// форма, поэтому нормализуем регистр, «ё» и лишние пробелы.
String normalizeMarkTitle(String title) => title
    .trim()
    .toLowerCase()
    .replaceAll('ё', 'е')
    .replaceAll(RegExp(r'\s+'), ' ');

/// Сокращения для узких столбцов таблицы оценок.
const Map<String, String> _shortTitles = {
  'отлично': 'Отл.',
  'хорошо': 'Хор.',
  'удовлетворительно': 'Удовл.',
  'зачет': 'Зач.',
  'незачет': 'Незач.',
  'не аттестован': 'Не атт.',
};

/// Короткая подпись аттестации; неизвестные значения отдаём как есть,
/// чтобы новая формулировка в API не превращалась в пустую ячейку.
String shortMarkTitle(String title) =>
    _shortTitles[normalizeMarkTitle(title)] ?? title.trim();
