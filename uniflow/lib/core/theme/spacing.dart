/// Шкала отступов UniFlow.
///
/// M3 не публикует шкалу отступов — это дизайн-решение, согласованное с
/// line-height типографики и шагом радиусов: база 4dp, как минимальный шаг
/// сетки Material.
///
/// Правило иерархии (по мотивам обсуждений spacing-систем в дизайн-сообществах):
/// отступ между однотипными карточками меньше, чем между заголовком и его
/// содержимым, а между секциями — больше обоих.
class AppSpacing {
  AppSpacing._();

  /// 4dp — внутри плотных строк (иконка ↔ подпись).
  static const double xxs = 4;

  /// 8dp — между карточками одного списка.
  static const double xs = 8;

  /// 12dp — внутри карточки между блоками.
  static const double sm = 12;

  /// 16dp — горизонтальные поля экрана.
  static const double md = 16;

  /// 24dp — между секциями.
  static const double lg = 24;

  /// 32dp — вокруг пустых состояний и крупных блоков.
  static const double xl = 32;

  /// 48dp — минимальный тач-таргет.
  static const double touchTarget = 48;

  /// Отступ между карточками в списке.
  static const double listGap = xs;

  /// Заголовок → содержимое.
  static const double headingGap = xxs;
}
